"""One completion of one prompt case, as written to results/<run>/attempts/."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, Field

from eval_harness.adapters.base import Usage
from eval_harness.harness.record import RunMeta, results_dir


class PromptAttempt(BaseModel):
    case_id: str
    run_id: str
    model: str
    repeat: int
    status: Literal["completed", "error"]
    output_text: str = ""
    usage: Usage = Field(default_factory=Usage)
    cost_usd: float = 0.0
    latency_seconds: float = 0.0
    request_settings: dict[str, Any] = Field(default_factory=dict)
    stop_reason: str | None = None
    # The frozen prompt this answered. A re-import that changes a case under the same id is
    # then visible on every record that answered the old one.
    prompt_version: str = ""
    error: str | None = None
    started_at: str = ""
    finished_at: str = ""
    # Read back from disk instead of generated by this invocation. Never written.
    reused: bool = Field(default=False, exclude=True)

    @property
    def output_sha(self) -> str:
        return hashlib.sha256(self.output_text.encode()).hexdigest()[:16]


def attempts_dir(run_id: str) -> Path:
    d = results_dir(run_id) / "attempts"
    d.mkdir(parents=True, exist_ok=True)
    return d


def attempt_path(run_id: str, case_id: str, repeat: int) -> Path:
    return attempts_dir(run_id) / f"{case_id}.{repeat}.json"


def save_attempt(rec: PromptAttempt) -> Path:
    path = attempt_path(rec.run_id, rec.case_id, rec.repeat)
    path.write_text(json.dumps(rec.model_dump(), indent=2, ensure_ascii=False) + "\n")
    return path


def load_attempt(run_id: str, case_id: str, repeat: int) -> PromptAttempt | None:
    path = attempt_path(run_id, case_id, repeat)
    if not path.exists():
        return None
    rec = PromptAttempt.model_validate_json(path.read_text())
    rec.reused = True
    return rec


def load_attempts(run_id: str) -> list[PromptAttempt]:
    out = []
    for path in sorted(attempts_dir(run_id).glob("*.json")):
        out.append(PromptAttempt.model_validate_json(path.read_text()))
    out.sort(key=lambda a: (a.case_id, a.repeat))
    return out


def load_run_meta(run_id: str) -> RunMeta | None:
    path = results_dir(run_id) / "run.json"
    return RunMeta.model_validate_json(path.read_text()) if path.exists() else None


def is_prompt_run(run_id: str) -> bool:
    path = results_dir(run_id) / "run.json"
    if not path.exists():
        return False
    try:
        return bool(json.loads(path.read_text()).get("kind") == "prompt")
    except (OSError, json.JSONDecodeError):
        return False
